function [measurement_body, bias_body] = simulate_gyro(...
        true_rate_body, previous_bias_body, dt, params)
    bias_body = previous_bias_body + ...
        params.gyro.bias_random_walk * sqrt(dt) * randn(3, 1);
    white_noise = chol(params.gyro.covariance, 'lower') * randn(3, 1) / sqrt(dt);
    measurement_body = params.gyro.misalignment * ...
        (true_rate_body + bias_body) + white_noise;
end