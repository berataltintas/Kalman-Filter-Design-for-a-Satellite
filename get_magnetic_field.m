function magnetic_field_eci = get_magnetic_field(position_eci, params)
    position_norm = norm(position_eci);
    position_unit = position_eci / position_norm;
    magnetic_field_eci = params.magnetic_field.surface_strength * ...
        (params.orbit.earth_radius / position_norm)^3 * ...
        (3 * dot(params.magnetic_field.axis, position_unit) * position_unit - ...
        params.magnetic_field.axis);
end